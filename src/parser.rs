pub enum Type {
    Int,
    Float,
    Char,
    String,
    Bool,
    Void,
    Fn,
}

pub enum ASTNodes {
    //Literal
    Str(String),
    Int(i64),
    Flt(f64),
    Char(char),
    Bool(bool),
    Lambda {
        arg: Vec<(Type, String)>,
        return_value: Type,
        body: Vec<Box<ASTNodes>>,
    },
    Identifier(String),
    Let {
        ty: Type,
        name: String,
        value: Box<ASTNodes>,
    },
    FnDef {
        name: String,
        arg: Vec<(Type, String)>,
        return_value: Type,
        body: Vec<Box<ASTNodes>>,
    },
    If {
        condition: Box<ASTNodes>,
        then_branch: Box<ASTNodes>,
        else_branch: Box<ASTNodes>,
    },
    Match {
        value: Box<ASTNodes>,
        arms: Vec<(Box<ASTNodes>, Box<ASTNodes>)>,
    },
    Loop {
        times: Box<ASTNodes>,
        process: Vec<Box<ASTNodes>>,
    },
    While {
        condition: Box<ASTNodes>,
        process: Vec<Box<ASTNodes>>,
    },
}

