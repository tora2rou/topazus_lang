fn parse_expr(tokens: &mut Peekable<Iter<Token>>) -> Result<ASTNodes, ParseError> {
    match tokens.peek() {
        Some(Token::Lparentheses) => parse_sexpr(tokens),
        Some(Token::Int(integer)) => {
            tokens.next();
            Ok(ASTNodes::Int(*integer))
        }
        Some(Token::Flt(float)) => {
            tokens.next();
            Ok(ASTNodes::Flt(*float))
        }
        Some(Token::Ident(boolean)) if boolean == "True" => {
            tokens.next();
            Ok(ASTNodes::Bool(true))
        }
        Some(Token::Ident(boolean)) if boolean == "False" => {
            tokens.next();
            Ok(ASTNodes::Bool(false))
        }
        Some(Token::Ident(otherwise)) => {
            let name = otherwise.clone();
            tokens.next();
            Ok(ASTNodes::Identifier(name))
        }
        None => Err(ParseError::UnexpectedEof),
        Some(t) => Err(ParseError::UnexpectedToken(format!("{:?}", t))),
    }
}

fn parse_sexpr(tokens: &mut Peekable<Iter<Token>>) -> Result<ASTNodes, ParseError> {
    tokens.next();
    match tokens.peek() {
        Some(Token::Ident(any)) => match any.as_str() {
            "let" => parse_let(tokens),
            "if" => parse_if(tokens),
            "match" => parse_match(tokens),
            "loop" => parse_loop(tokens),
            "while" => parse_while(tokens),
            otherwise => parse_apply(tokens),
        },
        Some(Token::Add) => parse_calc(tokens),
        Some(Token::Substract) => parse_calc(tokens),
        Some(Token::Multiply) => parse_calc(tokens),
        Some(Token::Division) => parse_calc(tokens),
        Some(Token::Surplus) => parse_calc(tokens),
        None => Err(ParseError::UnexpectedEof),
        Some(t) => Err(ParseError::UnexpectedToken(format!("{:?}", t))),
    }
}

fn judge_type(tokens: &mut Peekable<Iter<Token>>) -> Result<Type, ParseError> {
    let ty = match tokens.peek() {
        Some(Token::Ident(any)) => match any.as_str() {
            "int" => Ok(Type::Int),
            "float" => Ok(Type::Float),
            "char" => Ok(Type::Char),
            "string" => Ok(Type::String),
            "bool" => Ok(Type::Bool),
            "fn" => Ok(Type::Fn),
            otherwise => Err(ParseError::UnexpectedToken(format!("{:?}", otherwise))),
        },
        None => Err(ParseError::UnexpectedEof),
        Some(token) => Err(ParseError::UnexpectedToken(format!("{:?}", token))),
    };
    return ty;
}

fn parse_type(tokens: &mut Peekable<Iter<Token>>) -> Result<Type, ParseError> {
    if let Some(Token::Lbrackets) = tokens.peek() {
        tokens.next(); // [ を消費
    } else {
        let token = tokens.next();
        return Err(ParseError::UnexpectedToken(format!("{:?}", token)));
    }

    let ty = judge_type(tokens);

    tokens.next(); // Ident を消費
    if let Some(Token::Rbrackets) = tokens.peek() {
        tokens.next(); // ] を消費
    } else {
        let token = tokens.next();
        return Err(ParseError::UnexpectedToken(format!("{:?}", token)));
    }
    Ok(ty)
}

