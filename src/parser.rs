fn parse_let(tokens: &mut Peekable<Iter<Token>>) -> Result<ASTNodes, ParseError> {
    let ty = parse_type(tokens)?;

    let name = match tokens.peek() {
        Some(Token::Ident(name)) => Ok(name.clone()),
        None => Err(ParseError::UnexpectedEof),
        Some(t) => Err(ParseError::UnexpectedToken(format!("{:?}", t))),
    }?;
    tokens.next();

    if let Some(Token::LeftArrow) = tokens.peek() {
        tokens.next();
    } else {
        let token = tokens.next();
        return Err(ParseError::UnexpectedToken(format!("{:?}", token)));
    }
    match ty {
        Type::Fn => {}

        _ => {
            let value = parse_expr(tokens)?;
            Ok(ASTNodes::Let {
                ty,
                name,
                value: Box::new(value),
            })
        }
    }
}

